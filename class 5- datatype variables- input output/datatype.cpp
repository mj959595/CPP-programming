#include<iostream>
#include<string>
using namespace std;

int main()
{
    int age = 20;                 // Integer
    float height = 5.7;           // Float
    double percentage = 85.75;    // Double (replaced pi)
    char grade = 'A';             // Character
    bool isStudent = true;        // Boolean
    string name = "Ali";          // String

    cout << "Name: " << name << endl;
    cout << "Age: " << age << endl;
    cout << "Height: " << height << endl;
    cout << "Percentage: " << percentage << "%" << endl;
    cout << "Grade: " << grade << endl;
    cout << "Student Status: " << isStudent << endl;

    return 0;
}
